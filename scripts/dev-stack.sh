#!/usr/bin/env bash
# Start the whole humanip stack locally, in the background.
#
#   scripts/dev-stack.sh          build (cargo) and start everything
#   scripts/dev-stack.sh stop     stop everything started from .stack/pids
#   scripts/dev-stack.sh status   show which services are running
#
# Services and ports (see docs/self-host.md):
#   fake-stripe :12111 | appctl serve :8787 | gateway :1080/:8080/:9090
#   web-api :3000      | Vite console :1420
#
# State lives in .stack/ (gitignored): env (generated secrets, created once),
# data/ (the two SQLite files), gateway.yaml, logs/, pids.
# Set NO_BUILD=1 to skip `cargo build`.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STACK="$ROOT/.stack"
LOGS="$STACK/logs"
DATA="$STACK/data"
PIDS="$STACK/pids"
ENV_FILE="$STACK/env"

rand_hex() { openssl rand -hex "$1" 2>/dev/null || head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

is_running() { [ -n "${1:-}" ] && kill -0 "$1" 2>/dev/null; }

stop_all() {
	[ -f "$PIDS" ] || { echo "dev-stack: nothing to stop"; return 0; }
	# Reverse start order so dependents go first.
	tac "$PIDS" | while read -r name pid; do
		if is_running "$pid"; then
			# Kill the process group so child processes (bun, vite) go too.
			kill -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null || true
			echo "stopped $name ($pid)"
		fi
	done
	rm -f "$PIDS"
}

status() {
	[ -f "$PIDS" ] || { echo "dev-stack: not running"; return 0; }
	while read -r name pid; do
		if is_running "$pid"; then echo "up    $name ($pid)"; else echo "down  $name (see $LOGS/$name.log)"; fi
	done <"$PIDS"
}

port_in_use() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

wait_http() {
	local name="$1" url="$2" tries=60
	local pid
	pid="$(awk -v n="$name" '$1 == n { print $2 }' "$PIDS")"
	until is_running "$pid" && curl -fsS -o /dev/null --noproxy '*' "$url" 2>/dev/null; do
		tries=$((tries - 1))
		if [ "$tries" -le 0 ]; then
			echo "dev-stack: $name did not come up at $url; last log lines:" >&2
			tail -n 20 "$LOGS/$name.log" >&2 || true
			return 1
		fi
		sleep 0.5
	done
	echo "up    $name  $url"
}

# start NAME CMD...: run CMD detached in its own process group, log to .stack/logs.
start() {
	local name="$1"
	shift
	setsid "$@" >"$LOGS/$name.log" 2>&1 </dev/null &
	echo "$name $!" >>"$PIDS"
}

case "${1:-start}" in
stop) stop_all; exit 0 ;;
status) status; exit 0 ;;
start) ;;
*) echo "usage: $0 [start|stop|status]" >&2; exit 2 ;;
esac

if [ -f "$PIDS" ]; then
	echo "dev-stack: already started (scripts/dev-stack.sh stop first)" >&2
	status
	exit 1
fi

busy=""
for port in 12111 8787 1080 8080 9090 3000 1420; do
	if port_in_use "$port"; then busy="$busy $port"; fi
done
if [ -n "$busy" ]; then
	echo "dev-stack: ports already in use:$busy (stop whatever holds them first)" >&2
	exit 1
fi

mkdir -p "$LOGS" "$DATA"

# Shared secrets, generated once and reused across restarts.
if [ ! -f "$ENV_FILE" ]; then
	umask 077
	cat >"$ENV_FILE" <<EOF
BETTER_AUTH_SECRET=$(rand_hex 32)
HUMANIP_CONTROL_TOKEN=$(rand_hex 24)
STRIPE_WEBHOOK_SECRET=whsec_$(rand_hex 24)
GATEWAY_ADMIN_TOKEN=$(rand_hex 24)
EOF
	echo "dev-stack: generated secrets in $ENV_FILE"
fi
set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

PUBLIC_URL="http://localhost:1420"
LEDGER="$DATA/ledger.db"

cat >"$STACK/gateway.yaml" <<EOF
# Generated by scripts/dev-stack.sh. Local only: exits directly from this host.
socks_listen: 127.0.0.1:1080
http_listen: 127.0.0.1:8080
admin_listen: 127.0.0.1:9090
admin_token: \${GATEWAY_ADMIN_TOKEN}
allow_direct: true
accounts_db: $LEDGER
api_keys: []
providers:
  - name: local-direct
    exit_type: residential
    sourcing: verified
    price_per_gb: 1.0
    fraud_score: 5
    max_sticky_minutes: 129600
    latency_ms: 10
    upstream: { kind: direct }
EOF

if [ "${NO_BUILD:-0}" != "1" ]; then
	echo "dev-stack: cargo build -p appctl -p humanip-gateway"
	(cd "$ROOT" && cargo build -q -p appctl -p humanip-gateway)
fi
if [ ! -d "$ROOT/node_modules" ]; then
	(cd "$ROOT" && bun install)
fi

cd "$ROOT"

start fake-stripe env PORT=12111 \
	STRIPE_WEBHOOK_SECRET="$STRIPE_WEBHOOK_SECRET" \
	WEBHOOK_URL="http://127.0.0.1:8787/api/v1/billing/webhook" \
	bun run tools/fake-stripe/src/index.ts
wait_http fake-stripe http://127.0.0.1:12111/healthz

start appctl env HUMANIP_ACCOUNTS_DB="$LEDGER" \
	HUMANIP_CONTROL_TOKEN="$HUMANIP_CONTROL_TOKEN" \
	STRIPE_SECRET_KEY=sk_test_fake \
	STRIPE_WEBHOOK_SECRET="$STRIPE_WEBHOOK_SECRET" \
	HUMANIP_PUBLIC_URL="$PUBLIC_URL" \
	STRIPE_API_BASE=http://127.0.0.1:12111 \
	target/debug/appctl serve --host 127.0.0.1 --port 8787
wait_http appctl http://127.0.0.1:8787/healthz

start gateway env GATEWAY_ADMIN_TOKEN="$GATEWAY_ADMIN_TOKEN" \
	target/debug/humanip-gateway --config "$STACK/gateway.yaml"
wait_http gateway http://127.0.0.1:9090/healthz

start web-api env PORT=3000 \
	DATABASE_PATH="$DATA/auth.db" \
	BETTER_AUTH_SECRET="$BETTER_AUTH_SECRET" \
	PUBLIC_URL="$PUBLIC_URL" \
	CONTROL_URL=http://127.0.0.1:8787 \
	HUMANIP_CONTROL_TOKEN="$HUMANIP_CONTROL_TOKEN" \
	GATEWAY_HOST=localhost SOCKS_PORT=1080 HTTP_PORT=8080 \
	bun run apps/web-api/src/index.ts
wait_http web-api http://127.0.0.1:3000/healthz

start vite env VITE_API_PROXY=http://127.0.0.1:8787 \
	VITE_ADMIN_PROXY=http://127.0.0.1:9090 \
	bunx vite frontend --host 127.0.0.1
wait_http vite http://127.0.0.1:1420/

cat <<EOF

humanip dev stack is up. Open $PUBLIC_URL
  logs:  $LOGS/
  stop:  scripts/dev-stack.sh stop
  gateway admin token: see GATEWAY_ADMIN_TOKEN in $ENV_FILE
EOF
